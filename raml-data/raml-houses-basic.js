function ramlGetHouseBasic(houseNumber) {
  return RAML_HOUSES_BASIC[Number(houseNumber)] || {
    number: Number(houseNumber),
    hebrew: "",
    arabic: "",
    role: ""
  };
}

function ramlListHousesBasic() {
  return Object.keys(RAML_HOUSES_BASIC)
    .map(Number)
    .sort((a, b) => a - b)
    .map(n => RAML_HOUSES_BASIC[n]);
}

