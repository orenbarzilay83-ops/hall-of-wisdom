const SYM = { "\u2665": "H", "\u2666": "D", "\u2663": "C", "\u2660": "S" };
function norm(code) {
  const last = code.slice(-1);
  return SYM[last] ? code.slice(0, -1) + SYM[last] : code;
}
function rank(code) {
  return norm(code).slice(0, -1);
}
function suit(code) {
  return norm(code).slice(-1);
}
function valence(code, reversed) {
  const id = norm(code);
  const negCards = ["9S", "10S", "8S", "7S", "AS", "KS", "QS", "JS", "9D", "10D"].filter((c) => ["9S", "10S", "8S", "7S", "AS"].includes(c));
  const posCards = ["9H", "10H", "8H", "7H", "AH", "KH", "QH", "9C", "10C", "AC", "KC", "QC", "7D", "10D", "9D"];
  if (reversed) {
    if (posCards.includes(id)) return "neu";
    return "neg";
  }
  if (["9S", "10S", "8S", "7S", "AS", "KS", "QS", "JS"].includes(id)) return "neg";
  if (posCards.includes(id)) return "pos";
  return "neu";
}
function connector(prev, next) {
  const pv = valence(prev.code, prev.reversed);
  const nv = valence(next.code, next.reversed);
  if (pv === "pos" && nv === "neg") return "\u05D0\u05D1\u05DC";
  if (pv === "neg" && nv === "pos") return "\u05D5\u05DC\u05DE\u05E8\u05D5\u05EA \u05D6\u05D0\u05EA";
  if (pv === "neg" && nv === "neg") return "\u05D5\u05E2\u05DC \u05D2\u05D1\u05D9 \u05D6\u05D4";
  return "\u05D5\u05DC\u05D0\u05D7\u05E8 \u05DE\u05DB\u05DF";
}
