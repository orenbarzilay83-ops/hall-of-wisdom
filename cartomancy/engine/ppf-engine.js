function getCardStatement(card, profile) {
  const id = norm(card.code);
  const r = rank(card.code);
  const isCourt = ["K", "Q", "J"].includes(r);
  if (card.reversed) {
    return REVERSED[id] || `${id} (\u05D4\u05E4\u05D5\u05DA)`;
  }
  if (isCourt) {
    return courtStatement(id, profile);
  }
  return UPRIGHT[id] || id;
}
function buildSectionLines(cards, profile, groups) {
  const lines = [];
  if (groups.length > 0) {
    lines.push(`\u05E7\u05D1\u05D5\u05E6\u05D5\u05EA: ${groups.join(" | ")}`);
  }
  const statements = cards.map((c) => getCardStatement(c, profile));
  for (let i = 0; i < statements.length; i++) {
    if (i === 0) {
      lines.push(statements[i]);
    } else {
      const conn = connector(cards[i - 1], cards[i]);
      lines.push(`${conn} \u2014 ${statements[i]}`);
    }
  }
  return lines;
}
function buildPPFEngineConclusion(input) {
  const {
    pastCards,
    presentCards,
    futureCards,
    surpriseCards,
    pastGroups,
    presentGroups,
    futureGroups,
    profile
  } = input;
  const pastLines = buildSectionLines(pastCards, profile, pastGroups);
  const presentLines = buildSectionLines(presentCards, profile, presentGroups);
  const futureLines = buildSectionLines(futureCards, profile, futureGroups);
  const surpriseStatements = surpriseCards.map((c) => getCardStatement(c, profile));
  return [
    `=== \u05E2\u05D1\u05E8 ===`,
    pastLines.join("\n"),
    ``,
    `=== \u05D4\u05D5\u05D5\u05D4 ===`,
    presentLines.join("\n"),
    ``,
    `=== \u05E2\u05EA\u05D9\u05D3 ===`,
    futureLines.join("\n"),
    ``,
    `=== \u05D4\u05E4\u05EA\u05E2\u05D4 ===`,
    surpriseStatements.join(" | ")
  ].join("\n");
}
