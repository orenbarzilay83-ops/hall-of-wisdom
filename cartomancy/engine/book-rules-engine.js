function countSuits(cards) {
  return {
    hearts: cards.filter((card) => card.suit.key === "hearts").length,
    diamonds: cards.filter((card) => card.suit.key === "diamonds").length,
    clubs: cards.filter((card) => card.suit.key === "clubs").length,
    spades: cards.filter((card) => card.suit.key === "spades").length
  };
}
function countRanks(cards) {
  return {
    aces: cards.filter((card) => card.rank.key === "A").length,
    jacks: cards.filter((card) => card.rank.key === "J").length,
    queens: cards.filter((card) => card.rank.key === "Q").length,
    kings: cards.filter((card) => card.rank.key === "K").length,
    tens: cards.filter((card) => card.rank.key === "10").length
  };
}
function isAscending(cards) {
  const nums = cards.map((card) => card.rank.num);
  return nums.length === 3 && nums[0] < nums[1] && nums[1] < nums[2];
}
function isDescending(cards) {
  const nums = cards.map((card) => card.rank.num);
  return nums.length === 3 && nums[0] > nums[1] && nums[1] > nums[2];
}
function hasRepeatedNumber(cards) {
  const nums = cards.map((card) => card.rank.num);
  return new Set(nums).size < nums.length;
}
function allSameSuit(cards) {
  return cards.length > 0 && new Set(cards.map((card) => card.suit.key)).size === 1;
}
function allSameColor(cards) {
  return cards.length > 0 && new Set(cards.map((card) => card.color)).size === 1;
}
function hasWishCard(cards) {
  return cards.some((card) => card.rank.key === "9" && card.suit.key === "hearts");
}
function hasMaleGenderCard(cards) {
  return cards.some((card) => card.rank.key === "6" && card.suit.key === "hearts");
}
function hasDeathCard(cards) {
  return cards.some((card) => card.rank.key === "A" && card.suit.key === "spades");
}
function pushRule(results, rule) {
  if (!results.includes(rule)) {
    results.push(rule);
  }
}
