function shuffleDeck() {
  const deck = [...DECK_32];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}
function toDealt(code) {
  return { code, reversed: Math.random() < 0.3 };
}
function dealPPF(shuffled) {
  const surpriseCards = [shuffled[0], shuffled[31]].map(toDealt);
  const remaining = shuffled.slice(1, 31);
  return {
    surpriseCards,
    pastCards: remaining.slice(0, 10).map(toDealt),
    presentCards: remaining.slice(10, 20).map(toDealt),
    futureCards: remaining.slice(20, 30).map(toDealt)
  };
}
