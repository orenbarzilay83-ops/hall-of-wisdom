function detectPairs(rawCodes) {
  const rankCount = {};
  for (const code of rawCodes) {
    const rank = getRank(code);
    rankCount[rank] = (rankCount[rank] || 0) + 1;
  }
  const results = [];
  for (const [rank, count] of Object.entries(rankCount)) {
    if (count >= 2 && PAIR_MEANINGS[rank]) {
      const meaning = PAIR_MEANINGS[rank][count] || PAIR_MEANINGS[rank][2];
      if (meaning) results.push(meaning);
    }
  }
  return results;
}
function buildSection(rawCodes, sectionLabel) {
  const pairs = detectPairs(rawCodes);
  const pairsLine = pairs.length > 0 ? `\u05D6\u05D5\u05D2\u05D5\u05EA: ${pairs.join(" | ")}
` : "";
  const cardLines = rawCodes.map((code, i) => `${i + 1}. ${code} \u2014 ${cardMeaning(code)}`).join("\n");
  return `=== ${sectionLabel} ===
${pairsLine}${cardLines}`;
}
function buildPPFRawConclusion(input) {
  const { pastCards, presentCards, futureCards, surpriseCards, querentProfile } = input;
  const profileLine = querentProfile ? `\u05E4\u05E8\u05D5\u05E4\u05D9\u05DC \u05D4\u05E9\u05D5\u05D0\u05DC: ${querentProfile}

` : "";
  const surpriseLines = surpriseCards.map((code, i) => `${i + 1}. ${code} \u2014 ${cardMeaning(code)}`).join("\n");
  return [
    profileLine + buildSection(pastCards, "\u05E2\u05D1\u05E8"),
    buildSection(presentCards, "\u05D4\u05D5\u05D5\u05D4"),
    buildSection(futureCards, "\u05E2\u05EA\u05D9\u05D3"),
    `=== \u05D4\u05E4\u05EA\u05E2\u05D4 ===
${surpriseLines}`
  ].join("\n\n");
}
